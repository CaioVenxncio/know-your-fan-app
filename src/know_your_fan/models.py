"""Domain model for fictional fan profiles."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class FanProfile:
    """A fictional esports fan profile.

    Every field is generated by :mod:`know_your_fan.synthetic`. Profiles never
    contain real government identifiers, addresses, or contact details.
    """

    demo_id: str
    name: str
    city: str
    interests: tuple[str, ...]
    activities: tuple[str, ...]
    purchases: tuple[str, ...]
    social_links: tuple[str, ...]
    esports_profiles: tuple[str, ...]
